#!/usr/bin/env python3
"""Write docs/spawn_map.md: where enemy groups start on each floor and what they contain (from the ROM tables).

Reads the original ROM and the label names from tools/labels/rom.txt. Logic (UpdateBossAndSpawns):
- spawnStep moves one step per $18 scroll steps (FloorSpawnStep: $47 on floors going left, $03 going right).
- SpawnFloorN[spawnStep]: bit 2 set = no group here; else a group of 4 enemies (3 on floors 1-2 in the first
  round, curDefeatCount = 0) starts once groupWait has run out. Bits 0-1 != 0 select the slower SpawnDelays set
  ($10), bits 3-5 the SpawnSides pattern (pattern 2 = alternate is used instead while the player stands still).
- Each enemy's type comes from the byte at spawnStep + side: bits 6-7 = 0 gripper, $40 small enemy,
  $80/$C0 random gripper or small enemy.
- Knife throwers replace every Nth enemy from one side (ThrowerSpawnDelay); floors 2 and 4 start with their own
  events (Floor2Events, Floor4Events) and use this table only afterwards.
"""
import argparse, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROM_NAME = 'Spartan X (J) [!].nes'
BASE = 0x8000
FLOORS = 5
STEP_PIXELS = 0x18
NO_GROUP = 0x04
TYPE_NAMES = {0x00: 'gripper', 0x40: 'small', 0x80: 'gripper/small', 0xC0: 'gripper/small'}
SIDE_NAMES = ('front', 'back')      # SpawnSides 0: ahead of the player (in the facing direction), 1: behind
DIFFICULTY = ('0', '1', '2', '3+')


def labels():
    names = {}
    for line in open(os.path.join(ROOT, 'tools', 'labels', 'rom.txt'), encoding='utf-8'):
        m = re.match(r'^([0-9A-F]{4}) ([A-Za-z_]\w*)', line)
        if m:
            names[m.group(2)] = int(m.group(1), 16)
    return names


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--out', default=os.path.join(ROOT, 'docs', 'spawn_map.md'))
    args = ap.parse_args()
    prg = open(os.path.join(ROOT, ROM_NAME), 'rb').read()[16:16 + 0x8000]
    L = labels()
    rd = lambda a, n=0: prg[a - BASE + n]
    first_step = [rd(L['FloorSpawnStep'], k) for k in range(2)]
    # both tables are indexed by spawnLeft - 1, which counts down: shown in spawn order (index 3 first)
    sides = [[rd(L['SpawnSides'], p * 4 + k) for k in (3, 2, 1, 0)] for p in range(6)]
    delays = [[rd(L['SpawnDelays'], s + k) for k in (3, 2, 1, 0)] for s in range(0, 0x20, 4)]
    group = [[rd(L['GroupDelays'], f * 4 + d) for d in range(4)] for f in range(FLOORS)]
    thrower = [[rd(L['ThrowerSpawnDelay'], f * 4 + d) for d in range(4)] for f in range(FLOORS)]
    alt = [[rd(L['EnemyAltChance'], d * 4 + f - 1) if f else None for d in range(4)] for f in range(FLOORS)]
    out = ['# Enemy spawn map',
           '',
           'Generated by `tools/spawn_map.py` from the ROM tables; see its docstring and `UpdateBossAndSpawns`.',
           'A group starts whenever `groupWait` has run out; the floor tables below say what kind of group starts',
           'at each position. Distances are scroll pixels from the floor start (one `spawnStep` = %d px).' % STEP_PIXELS,
           'Floors 1, 3 and 5 are'
           ' walked leftwards (`spawnStep` counts down from $%02X), floors 2 and 4 rightwards (up from $%02X).'
           % tuple(first_step),
           '',
           '- A group has 4 enemies (3 on floors 1 and 2 in the first round). Before a group starts, `groupWait`',
           '  runs out (frames by floor and difficulty, +$30 in game A):',
           '',
           '| Floor | ' + ' | '.join('difficulty %s' % d for d in DIFFICULTY) + ' |',
           '|---|' + '---|' * 4]
    out += ['| %d | %s |' % (f + 1, ' | '.join(str(v) for v in group[f])) for f in range(FLOORS)]
    out += ['',
            '- Every Nth enemy that comes from one side is a knife thrower instead (`ThrowerSpawnDelay`, +2 in',
            '  game A on floors 2-5; not on floor 5 before scroll page 2):',
            '',
            '| Floor | ' + ' | '.join('difficulty %s' % d for d in DIFFICULTY) + ' |',
            '|---|' + '---|' * 4]
    out += ['| %d | %s |' % (f + 1, ' | '.join(str(v) for v in thrower[f])) for f in range(FLOORS)]
    out += ['',
            '- A new small enemy gets `OBJST_ALT` (alternative behaviour) when its random byte is at',
            '  or above `EnemyAltChance` (0 = never). Floor 1 has only grippers, so its index ($FF, past the',
            '  table start) is never used:',
            '',
            '| Floor | ' + ' | '.join('difficulty %s' % d for d in DIFFICULTY) + ' |',
            '|---|' + '---|' * 4]
    out += ['| %d | %s |' % (f + 1, ' | '.join('-' if v is None else ('never' if v == 0 else '$%02X' % v)
                                               for v in alt[f])) for f in range(FLOORS)]
    out += ['',
            '- Side patterns (`SpawnSides`, in spawn order; a group of 3 uses the last three; front = ahead of',
            '  the player, back = behind):',
            '']
    out += ['  %d: %s' % (p, ', '.join(SIDE_NAMES[s] for s in sides[p])) for p in range(6)]
    out += ['',
            '- Frames between the enemies of a group (`SpawnDelays`): delay set A = $00-$0C (spawn byte bits 0-1 = 0),',
            '  B = $10-$1C (bits 0-1 != 0); a random one of the 4 sets inside A or B. While the player stands still',
            '  (no scroll for `timersSlow+6`) every delay is $38 and the side pattern is 2. Frames after each enemy,',
            '  in spawn order:',
            '']
    out += ['  set $%02X (%s): %s' % (s * 4, 'AB'[s >= 4], ', '.join(str(v) for v in delays[s])) for s in range(len(delays))]
    events = {1: 'Floor 2 starts with `Floor2Events` (objects dropped from the ceiling) until scroll page 3.',
              3: 'Floor 4 starts with `Floor4Events` (flyers) until the player reaches page 4.'}
    for f in range(FLOORS):
        table = L['SpawnFloor%d' % (f + 1)]
        right = f & 1
        out += ['', '## Floor %d (%s)' % (f + 1, 'rightwards' if right else 'leftwards'), '']
        if f in events:
            out += [events[f], '']
        if f == 0:
            out += ["Types are given for a player facing the floor's direction (front = the side ahead); a player",
                    'facing backwards swaps front and back. "gripper/small" = random. Delay set B: how many of the',
                    'merged steps select set B.', '']
        out += ['| spawnStep | Distance (px) | Sides | Types (front / back) | Delay set B |', '|---|---|---|---|---|']
        steps = range(first_step[1], first_step[0] + 1) if right else range(first_step[0], first_step[1] - 1, -1)
        rows = []                                       # [key, first step, last step, steps with set B]
        for st in steps:
            b = rd(table, st)
            if b & NO_GROUP:
                key = None
            else:
                pat = b >> 3 & 7
                # the type byte is read at spawnStep + ptr_00, ptr_00 = SpawnSides value ^ (playerAction & PA_RIGHT):
                # for a player facing the floor's direction "front" is +1 on rightward floors, +0 on leftward ones
                types = tuple(TYPE_NAMES[rd(table, st + k) & 0xC0] for k in ((1, 0) if right else (0, 1)))
                key = (pat, types)
            if rows and rows[-1][0] == key:
                rows[-1][2] = st
            else:
                rows.append([key, st, st, 0, 0])
            rows[-1][3] += key is not None and bool(b & 3)
            rows[-1][4] += 1
        for key, a, z, nb, n in rows:
            dist = lambda st: abs(st - first_step[right]) * STEP_PIXELS
            where = '$%02X' % a if a == z else '$%02X-$%02X' % (a, z)
            span = '%d' % dist(a) if a == z else '%d-%d' % (dist(a), dist(z))
            if key is None:
                out.append('| %s | %s | no group | | |' % (where, span))
                continue
            pat, (tf, tb) = key
            out.append('| %s | %s | %d (%s) | %s / %s | %d of %d |' % (
                where, span, pat, ' '.join(SIDE_NAMES[x][0].upper() for x in sides[pat]) if pat < len(sides)
                else '?', tf, tb, nb, n))
    with open(args.out, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(out) + '\n')
    print(os.path.relpath(args.out, ROOT))


if __name__ == '__main__':
    main()
